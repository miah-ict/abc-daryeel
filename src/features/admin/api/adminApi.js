import {api} from '../../../services/api'
export const getStudents=()=>api('/students')
export const createStudent=body=>api('/students',{method:'POST',body})
export const updateStudent=(id,body)=>api(`/students/${encodeURIComponent(id)}`,{method:'PUT',body})
export const markAttendance=body=>api('/attendance',{method:'POST',body})
export const createUser=body=>api('/users',{method:'POST',body})
export const updateUser=(id,body)=>api(`/users/${encodeURIComponent(id)}`,{method:'PUT',body})
export const createClass=body=>api('/classes',{method:'POST',body})
export const updateClass=(id,body)=>api(`/classes/${encodeURIComponent(id)}`,{method:'PUT',body})
export const getExams=()=>api('/exams')
export const createExam=body=>api('/exams',{method:'POST',body})
export const publishExam=id=>api(`/exams/${encodeURIComponent(id)}/publish`,{method:'POST'})
export const cancelExam=(id,reason)=>api(`/exams/${encodeURIComponent(id)}/cancel`,{method:'POST',body:{reason}})
export const getExamResults=id=>api(`/exams/${encodeURIComponent(id)}/results`)
export const setFailedDecision=(examId,studentId,decision)=>api(`/exams/${encodeURIComponent(examId)}/results/${encodeURIComponent(studentId)}/decision`,{method:'PUT',body:{decision}})
export const reopenExamAssignment=(id,reason)=>api(`/exams/assignments/${encodeURIComponent(id)}/reopen`,{method:'POST',body:{reason}})
export const getCourses=id=>api(`/exams/${encodeURIComponent(id)}/courses`)
export const addCourseStudent=(id,body)=>api(`/exams/${encodeURIComponent(id)}/courses`,{method:'POST',body})
export const getAcademicYears=()=>api('/academic-years')
export const createAcademicYear=body=>api('/academic-years',{method:'POST',body})
export const startAcademicYear=id=>api(`/academic-years/${encodeURIComponent(id)}/start`,{method:'POST'})
